def to_bool_nullable(values, what):
    """Like to_bool, but a blank becomes NULL (outlier_flag: 38 rows not tested
    in Phase 3 - NOT the same as False). Anything else unexpected still stops."""
    b = values.str.lower().map({"true": True, "false": False})
    bad = sorted(values[values.notna() & b.isna()].unique())
    assert not bad, f"{what}: values that are not true/false/blank: {bad}"
    return b.astype("boolean")    # lowercase 'boolean': True/False that can hold a blank


unit_ids = lookup("dim_unit", "unit_id", "unit_name")

print("Loading facts:")

# fact_price - grain: market, commodity, month, unit, price type.
# Market and commodity are WFP ids already in the file: the foreign keys guard
# them. Unit is looked up. price_per_kg is NOT loaded (computed in SQL instead).
fact_price = pd.DataFrame({
    "market_id":      prices["market_id"].astype(int),
    "commodity_id":   prices["commodity_id"].astype(int),
    # The text '2006-01-01' becomes a real date. format= makes pandas refuse
    # anything that isn't year-month-day, instead of guessing.
    "month_start":    pd.to_datetime(prices["month"], format="%Y-%m-%d").dt.date,
    "unit_id":        map_required(prices["unit"], unit_ids, "price unit"),
    "price_type":     prices["pricetype"],
    "price_flag":     prices["priceflag"],
    "price_ghs":      prices["price"].map(Decimal),           # exact cedis and pesewas
    "outlier_ratio":  prices["outlier_ratio"].astype(float),  # Python's 64-bit value, unchanged
    "outlier_flag":   to_bool_nullable(prices["outlier_flag"], "outlier_flag"),
    "series_suspect": to_bool(prices["series_suspect"], "series_suspect"),
    "unit_suspect":   to_bool(prices["unit_suspect"], "unit_suspect"),
})
load_table(fact_price, "fact_price")

# fact_yield - long shape: one value per element, item, year. item_code stays text.
