from decimal import Decimal


def lookup(table, id_col, name_col):
    """Read a dimension back FROM SQL SERVER as {name: id}. SQL Server assigned
    the ids, so it is the only place that knows them."""
    df = pd.read_sql(f"SELECT {id_col}, {name_col} FROM dbo.{table}", engine)
    return dict(zip(df[name_col], df[id_col]))


def map_required(values, mapping, what):
    """Every value must match. Stops and NAMES any that don't (e.g. 'BRONG-AHAFO')."""
    ids = values.map(mapping)
    missing = sorted(values[ids.isna()].unique())
    assert not missing, f"{what}: not in the dimension: {missing}"
    return ids.astype(int)


def map_optional(values, mapping, what):
    """Blank -> NULL (onions: not one of our crops, which is true).
    Filled in but matching nothing -> stop (a typo would otherwise load as NULL
    and look exactly like onions)."""
    ids = values.map(mapping)
    unmatched = sorted(values[values.notna() & ids.isna()].unique())
    assert not unmatched, f"{what}: filled in but not in the dimension: {unmatched}"
    # Int64 (capital I): pandas' integer type that can hold a blank.
    # Plain int can't, so pandas would silently turn the column into floats.
    return ids.astype("Int64")


def to_bool(values, what):
    """'True'/'TRUE'/'false'... -> True/False. Anything else stops the script.
    markets.csv writes True/False; crop_calendar.csv writes TRUE/FALSE."""
    b = values.str.lower().map({"true": True, "false": False})
    assert b.notna().all(), f"{what}: values that are not true/false: {sorted(values[b.isna()].unique())}"
    return b


region_ids = lookup("dim_region", "region_id", "region_name")
crop_ids   = lookup("dim_crop",   "crop_id",   "crop_name")

print("Loading dependent dimensions:")

# dim_market - WFP's own id as the key; region looked up; currency of
# countryiso3 dropped (GHA in every row).
dim_market = pd.DataFrame({
    "market_id":     markets["market_id"].astype(int),
    "market_name":   markets["market"],
    "region_id":     map_required(markets["admin1"], region_ids, "market region"),
    "district_name": markets["admin2"],
    "latitude":      markets["latitude"].map(Decimal),    # exact, as published
    "longitude":     markets["longitude"].map(Decimal),
    "short_panel":   to_bool(markets["short_panel"], "short_panel"),
})
load_table(dim_market, "dim_market")

# dim_commodity - one row per WFP commodity, taken from the price rows.
comm = prices[["commodity_id", "commodity", "category", "crop"]].drop_duplicates()
# One name per id was checked on 31 Oct; now it is enforced on every run.
assert comm["commodity_id"].is_unique, "a commodity_id carries two names, categories or crops"
dim_commodity = pd.DataFrame({
    "commodity_id":   comm["commodity_id"].astype(int),
    "commodity_name": comm["commodity"],
    "category":       comm["category"],
    "crop_id":        map_optional(comm["crop"], crop_ids, "commodity crop"),
}).sort_values("commodity_id")
load_table(dim_commodity, "dim_commodity")

# dim_crop_calendar - as published: dekads kept, borrowed rows kept and labelled.
# The two CHECK constraints (dekads 1-36; wrap flag agrees with the numbers)
# are tested here for the first time, on real rows.
dim_crop_calendar = pd.DataFrame({
    "region_id":            map_required(calendar["region"], region_ids, "calendar region"),
    "region_published":     calendar["region_published"],        # blank on 4 borrowed rows -> NULL
    "crop_id":              map_required(calendar["crop"], crop_ids, "calendar crop"),
    "crop_name":            calendar["crop_name"],
    "sos_s":                calendar["sos_s"].astype(int),
    "sos_e":                calendar["sos_e"].astype(int),
    "eos_s":                calendar["eos_s"].astype(int),
    "eos_e":                calendar["eos_e"].astype(int),
    "harvest_crosses_year": to_bool(calendar["harvest_crosses_year"], "harvest_crosses_year"),
    "calendar_source":      calendar["calendar_source"],
})
load_table(dim_crop_calendar, "dim_crop_calendar")

# dim_fao_item - item_code stays TEXT ('0112', '01520.01'); crop optional.
items = fao[["item_code", "item", "crop"]].drop_duplicates()
assert items["item_code"].is_unique, "an item_code carries two names or crops"
dim_fao_item = pd.DataFrame({
    "item_code": items["item_code"],
    "item_name": items["item"],
    "crop_id":   map_optional(items["crop"], crop_ids, "FAO item crop"),
}).sort_values("item_code")
load_table(dim_fao_item, "dim_fao_item")


