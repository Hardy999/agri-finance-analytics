# ---------------------------------------------------------------------------
# Section 6: independent checks - the warehouse against the clean files
# ---------------------------------------------------------------------------

print("Checks:")

# Check A: per-kg price computed TWO WAYS must agree on every row.
#   way 1: SQL Server, now, from price_ghs and dim_unit.unit_kg
#   way 2: clean.py's price_per_kg, computed in Python in October
q = """
SELECT f.market_id, f.commodity_id, f.month_start, u.unit_name, f.price_type,
       f.price_ghs,
       f.price_ghs / u.unit_kg AS per_kg_sql     -- NULL where unit_kg is NULL
FROM dbo.fact_price AS f
JOIN dbo.dim_unit   AS u ON u.unit_id = f.unit_id
"""
wh = wh = pd.read_sql(q, engine, coerce_float=False)
wh["month_start"] = wh["month_start"].astype(str)        # '2006-01-01', same as the CSV

clean = prices.rename(columns={"month": "month_start", "unit": "unit_name",
                               "pricetype": "price_type"})
clean["market_id"] = clean["market_id"].astype(int)
clean["commodity_id"] = clean["commodity_id"].astype(int)

keys = ["market_id", "commodity_id", "month_start", "unit_name", "price_type"]
# validate="one_to_one": pandas itself refuses if a key appears twice on either
# side. indicator=True adds a column saying where each row was found.
both = wh.merge(clean, on=keys, how="outer", validate="one_to_one", indicator=True)

# 1. Every row found on both sides - nothing extra, nothing missing.
assert (both["_merge"] == "both").all(), both["_merge"].value_counts().to_dict()


# 2. Price identical to the published value, exactly (Decimal vs Decimal).
assert (both["price_ghs"] == both["price"].map(Decimal)).all(), "price_ghs differs from the clean file"

# 3. Blank per-kg in exactly the same rows (non-weight units).
sql_kg   = both["per_kg_sql"].astype(float)
clean_kg = both["price_per_kg"].astype(float)
assert (sql_kg.isna() == clean_kg.isna()).all(), "per-kg is blank on one side only"

# 4. Where both have a value, they agree to within 0.000000001.
diff = (sql_kg - clean_kg).abs().max()
assert diff < 1e-9, f"per-kg differs by up to {diff}"

print(f"  A. per-kg two ways: {len(both)} rows matched, "
      f"{sql_kg.isna().sum()} without a kg unit, max difference {diff:.2e}")


# Check B: one total, three ways. A CHECKSUM, not a statistic - it adds
# prices in different units, which means nothing except as a fingerprint:
# any lost, duplicated or altered price would change it.
by_region = pd.read_sql("""
    SELECT r.region_name, COUNT(*) AS n, SUM(f.price_ghs) AS total
    FROM dbo.fact_price AS f
    JOIN dbo.dim_market AS m ON m.market_id = f.market_id
    JOIN dbo.dim_region AS r ON r.region_id = m.region_id
    GROUP BY r.region_name
""", engine, coerce_float=False)
direct = pd.read_sql("SELECT COUNT(*) AS n, SUM(price_ghs) AS total FROM dbo.fact_price",
                     engine, coerce_float=False)
from_csv_total = sum(prices["price"].map(Decimal))     # Decimal arithmetic: exact

assert by_region["n"].sum() == direct["n"][0] == len(prices), "row counts disagree"
assert by_region["total"].sum() == direct["total"][0] == from_csv_total, "price totals disagree"
print(f"  B. {len(by_region)} regions re-sum to {direct['n'][0]} rows and "
      f"GHS {direct['total'][0]} - same as the direct total and the CSV")

# Check C: FAOSTAT round trip. Matching on item_code is itself the test that
# it stayed text: '0112' turned into 112 anywhere would fail to match.
fy = pd.read_sql("SELECT element_code, item_code, fao_year, value AS value_sql FROM dbo.fact_yield",
                 engine, coerce_float=False)
fc = fao.assign(element_code=fao["element_code"].astype(int), fao_year=fao["year"].astype(int))
y = fy.merge(fc, on=["element_code", "item_code", "fao_year"],
             how="outer", validate="one_to_one", indicator=True)
assert (y["_merge"] == "both").all(), y["_merge"].value_counts().to_dict()
assert (y["value_sql"].isna() == y["value"].isna()).all(), "FAOSTAT blanks differ"
has = y["value"].notna()
assert (y.loc[has, "value_sql"] == y.loc[has, "value"].map(Decimal)).all(), "FAOSTAT values differ"
print(f"  C. FAOSTAT: {len(y)} rows matched, {(~has).sum()} blank on both sides, values identical")

# Check D: policy-rate round trip.
fr = pd.read_sql("SELECT effective_date, policy_rate_pct FROM dbo.fact_rate",
                 engine, coerce_float=False)
fr["effective_date"] = fr["effective_date"].astype(str)
r = fr.merge(bog, on="effective_date", how="outer", validate="one_to_one", indicator=True)
assert (r["_merge"] == "both").all(), r["_merge"].value_counts().to_dict()
assert (r["policy_rate_pct"] == r["policy_rate"].map(Decimal)).all(), "policy rates differ"
print(f"  D. policy rate: {len(r)} rows matched, rates identical")

print("All checks passed.")