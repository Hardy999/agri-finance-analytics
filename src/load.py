"""
load.py - Phase 4: load the clean files into the AgriFinance warehouse.

Run from the project root:   .venv\\Scripts\\python.exe src\\load.py

Reads data/clean/*.csv and fills the tables built by sql/01-13.
dim_date is generated by sql/05_dim_date.sql and is never touched here.
"""

import pandas as pd
from sqlalchemy import text

# db.py is the one place that knows how to reach SQL Server (Phase 0).
# This import works because Python puts the running script's own folder
# (src/) on its search path, and db.py lives there too.
from db import get_engine, PROJECT_ROOT

CLEAN = PROJECT_ROOT / "data" / "clean"
EXPECTED_DB = "AgriFinance"


# ---------------------------------------------------------------------------
# Section 1: connect, and refuse the wrong database
# ---------------------------------------------------------------------------

# fast_executemany: batches instead of one round trip per row.
# Without it, 37,676 price rows take minutes, not seconds.
engine = get_engine(fast_executemany=True)

# Ask the SERVER where we are. config.ini only says what we asked for;
# on 28 Oct the two disagreed without any warning.
with engine.connect() as conn:
    db = conn.execute(text("SELECT DB_NAME()")).scalar()
print(f"Connected to: {db}")
assert db == EXPECTED_DB, f"connected to {db!r}, expected {EXPECTED_DB!r} - check config.inid to {db!r}, expected {EXPECTED_DB!r} - check config.ini"


# ---------------------------------------------------------------------------
# Section 2: empty every table this script fills, children before parents
# ---------------------------------------------------------------------------

# Order matters: a parent row can't be deleted while a foreign key still
# points at it. Facts first, then dimensions that point at other dimensions,
# then the parents. dim_date is NOT here: generated in SQL, never loaded.
CHILDREN_FIRST = [
    
    "fact_price", "fact_yield", "fact_rate",
    "dim_crop_calendar", "dim_market", "dim_commodity", "dim_fao_item",
    "dim_region", "dim_crop", "dim_unit", "dim_fao_element", "dim_fao_flag",
]
# The three tables whose keys SQL Server generates (IDENTITY).
IDENTITY_TABLES = ["dim_region", "dim_crop", "dim_unit"]

# begin(): one transaction. Commits if the block finishes, undoes EVERYTHING
# if any statement fails. (connect() would not commit at all.)
with engine.begin() as conn:
    for t in CHILDREN_FIRST:
        # DELETE, not TRUNCATE: TRUNCATE is refused on any table a foreign
        # key points at, even an empty one. Table names come from our own
        # list above, never from a file or a user, so building SQL from
        # them is safe.
        conn.execute(text(f"DELETE FROM dbo.{t}"))

    for t in IDENTITY_TABLES:
        # Restart numbering at 1 - but ONLY on a table that has handed out
        # an ID before. On a never-used table, RESEED 0 makes the next row 0,
        # so the first run would number from 0 and every later run from 1.
        conn.execute(text(f"""
            IF EXISTS (SELECT 1 FROM sys.identity_columns
                       WHERE object_id = OBJECT_ID('dbo.{t}')
                         AND last_value IS NOT NULL)
                DBCC CHECKIDENT ('dbo.{t}', RESEED, 0) WITH NO_INFOMSGS;
        """))

# Check the result, not the return value: count what's actually left.
with engine.connect() as conn:
    for t in CHILDREN_FIRST:
        n = conn.execute(text(f"SELECT COUNT(*) FROM dbo.{t}")).scalar()
        assert n == 0, f"{t} still has {n} rows after clearing"
print(f"Cleared {len(CHILDREN_FIRST)} tables (dim_date left alone).")


# ---------------------------------------------------------------------------
# Section 3: read the clean files, load the five parent dimensions
# ---------------------------------------------------------------------------

# dtype=str everywhere: nothing is converted on the way in. item_code keeps
# its leading zeros; numbers are converted deliberately, column by column.
markets  = pd.read_csv(CLEAN / "markets.csv",         dtype=str)
calendar = pd.read_csv(CLEAN / "crop_calendar.csv",   dtype=str)
prices   = pd.read_csv(CLEAN / "prices.csv",          dtype=str)
fao      = pd.read_csv(CLEAN / "faostat_qcl.csv",     dtype=str)
bog      = pd.read_csv(CLEAN / "bog_policy_rate.csv", dtype=str, encoding="utf-8")


def load_table(df, table):
    """Append df to an existing table, then prove it arrived by counting in SQL."""
    # append: fill OUR table. 'replace' would drop it and recreate it with
    # pandas' guesses - no keys, no constraints, no error message.
    # index=False: don't send pandas' row numbers as a column called 'index'.
    df.to_sql(table, engine, schema="dbo", if_exists="append", index=False)
    with engine.connect() as conn:
        n = conn.execute(text(f"SELECT COUNT(*) FROM dbo.{table}")).scalar()
    assert n == len(df), f"{table}: {n} rows in SQL Server, {len(df)} sent"
    print(f"  {table:<18} {n:>6} rows")


print("Loading parent dimensions:")

# dim_region - every region either file uses (identical sets, checked 29 Oct;
# the union means a region in only one of them would still get a row).
# sorted(): fixes the insert order, so region_id is the same on every run.
regions = sorted(set(markets["admin1"]) | set(calendar["region"]))
load_table(pd.DataFrame({"region_name": regions}), "dim_region")

# dim_crop - the X2 crop values from all three files. Blanks are not crops.
crops = sorted(set(prices["crop"].dropna())
               | set(fao["crop"].dropna())
               | set(calendar["crop"].dropna()))
load_table(pd.DataFrame({"crop_name": crops}), "dim_crop")

# dim_unit - one row per unit with its kg conversion.
units = prices[["unit", "unit_kg"]].drop_duplicates()
# If any unit carried two different unit_kg values it would appear twice
# here: the 31 Oct check, now enforced on every run.
assert units["unit"].is_unique, "a unit carries more than one unit_kg"
units = (units.rename(columns={"unit": "unit_name"})
              .astype({"unit_kg": float})      # blank -> NaN -> NULL in SQL
              .sort_values("unit_name"))
load_table(units, "dim_unit")

# dim_fao_element - taken from rows that HAVE a unit: the 150 blank cowpea
# rows have none, and would otherwise add a second, unit-less copy of each element.
elements = fao.loc[fao["unit"].notna(), ["element_code", "element", "unit"]].drop_duplicates()
assert elements["element_code"].is_unique, "an element carries more than one unit"
elements = (elements.rename(columns={"element": "element_name"})
                    .astype({"element_code": int})
                    .sort_values("element_code"))
load_table(elements, "dim_fao_element")

# dim_fao_flag - one row per flag code with its description.
flags = fao[["flag", "flag_description"]].dropna().drop_duplicates()
assert flags["flag"].is_unique, "a flag code carries more than one description"
flags = flags.rename(columns={"flag": "flag_code"}).sort_values("flag_code")
load_table(flags, "dim_fao_flag")


